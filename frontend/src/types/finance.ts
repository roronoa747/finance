export type Goal = Tracked & {
  id: string
  name: string
  need: number
  /**
   * Сумма, с которой цель завели. Дальше не меняется сама по себе —
   * только явным редактированием.
   */
  seed: number
  /**
   * Когда seed последний раз правили руками («Уже накоплено») — якорь, как
   * `Credit.principalSetAt`. Слияние берёт seed стороны с поздним якорем: взнос
   * партнёра, сделанный позже офлайн, двигает `updatedAt`, но правку не откатывает.
   */
  seedSetAt?: string | null
  /**
   * Накопленное = seed + сумма всех взносов. Всегда пересчитывается, никогда
   * не правится напрямую.
   *
   * Так сделано ради слияния: если оба сделали взнос офлайн, побеждать по
   * времени нельзя — один взнос просто исчезнет. Взносы объединяются по
   * идентификатору, а сумма считается заново из объединённого списка.
   */
  have: number
  monthly: number
  hue: HueKey
  /** Доля 0..1, где цель должна быть по плану на сегодня. */
  planPct: number
  movements: GoalMovement[]
  /**
   * Счёт, на котором физически лежат накопления цели.
   * Пока не задан, накопления считаются отдельным активом — иначе введённое
   * «уже накоплено» нигде бы не учитывалось и капитал уходил бы в минус.
   */
  accountId?: string | null
  /**
   * Прежняя «главная мечта» (Р-8, B2C-14) — больше не пишется (Р-84): главная — первая цель очереди `goalOrder`.
   * Читается один раз: пока порядка нет, отмеченная (поздняя по `updatedAt`) встаёт в очереди первой (`queueOf`).
   */
  main?: boolean
  /** Фото цели на сервере (B2C-16/17): в документе только id; null — фото убрали. */
  photoId?: string | null
  /** Автор картинки шаблона (Unsplash, Р-28) — показывается у мечты; своё фото — null. */
  photoCredit?: { author: string; url: string } | null
  /** Шаблон, из которого сделана цель (`lib/goalTemplates`); без `photoId` — картинка ещё не загружена. */
  template?: string | null
  /** Кто откладывает в цель (Р-80); пусто — первый участник семьи (`payerOf`). */
  payer?: PersonId | null
  /** Фонд (Р-82): «Запас» или «Подушка» — цель с порогом в месяцах трат; пусто — мечта. */
  fund?: 'reserve' | 'cushion' | null
  /** Порог фонда в месяцах трат (Р-82); пусто — умолчание `moneySettings` (запас 1, подушка 3). */
  fundMonths?: number
  /** Цель выключена в плане месяца (Р-83) — с этой даты, пока не включат; null — включена. */
  pausedAt?: string | null
  /** «Сбылось» (PN-13, Р-13): ISO момента отметки — деньги ушли покупкой, цель в альбоме; null — вернули в мечты. */
  doneAt?: string | null
  /** Поездка (PN-30, Р-14): первый и последний день `YYYY-MM-DD` включительно; null — дат нет. */
  from?: string | null
  to?: string | null
  /** Бюджет поездки, целые тенге; пусто — `need` (`tripSpent`). */
  budget?: number | null
}

