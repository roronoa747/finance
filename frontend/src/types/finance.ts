import type { AccentKey, CategoryKey, HueKey, ThemeChoice } from '@/lib/palette'

export type PersonId = 'a' | 'b' | 'c'

/**
 * Всё, что синхронизируется, несёт отметку времени и метку удаления.
 *
 * updatedAt нужен, чтобы при слиянии двух устройств выигрывала последняя
 * правка КАЖДОЙ сущности по отдельности, а не всего документа целиком —
 * иначе переименование цели на одном телефоне затрёт новую цель на другом.
 *
 * deletedAt нужен, потому что удаление вырезанием из массива при синхронизации
 * не работает: у партнёра запись осталась, и она вернётся обратно. Удалённое
 * помечается и продолжает ездить между устройствами как надгробие.
 */
export type Tracked = {
  updatedAt: string
  deletedAt?: string | null
}

export type Person = Tracked & {
  id: PersonId
  name: string
  /**
   * Текущий оклад без бонусов. Остаётся как значение по умолчанию,
   * когда версий ещё нет.
   */
  salary: number
  /**
   * Версии оклада с месяцем вступления в силу — как у обязательств.
   * Правка одним полем затирала прошлое: месячные срезы за прошедшие
   * месяцы пересчитывались по новой зарплате и переставали сходиться
   * с реальностью.
   */
  salaryVersions?: ObligationVersion[]
  /** День месяца, когда приходит зарплата. У двоих он разный. */
  payday: number
  /**
   * Когда участник закончил свою часть настройки.
   *
   * Раньше признаком служила зарплата больше нуля — и это было ошибкой:
   * ноль бывает законным (декрет, между работами), а любое обнуление данных
   * заново открывало мастер и зацикливало его.
   */
  onboardedAt?: string | null
}

export type Category = Tracked & {
  key: CategoryKey
  name: string
  note: string
  amount: number
}

export type GoalMovement = {
  id: string
  /** ISO-дата */
  date: string
  /** Со знаком: минус — забрали из цели обратно. */
  amount: number
  by: PersonId
  note?: string
  /**
   * Снятие «вложить уже накопленное» по плану «Сначала долги» (клинап Блока 3): id плана —
   * накопленное снимается в долг один раз, сколько бы шаг ни снимали и ни вносили.
   */
  planId?: string
}

export type Goal = Tracked & {
  id: string
  name: string
  need: number
  /**
   * Сумма, с которой цель завели. Дальше не меняется сама по себе —
   * только явным редактированием.
   */
  seed: number
  /**
   * Накопленное = seed + сумма всех взносов. Всегда пересчитывается, никогда
   * не правится напрямую.
   *
   * Так сделано ради слияния: если оба сделали взнос офлайн, побеждать по
   * времени нельзя — один взнос просто исчезнет. Взносы объединяются по
   * идентификатору, а сумма считается заново из объединённого списка.
   */
  have: number
  monthly: number
  hue: HueKey
  /** Доля 0..1, где цель должна быть по плану на сегодня. */
  planPct: number
  movements: GoalMovement[]
  /**
   * Счёт, на котором физически лежат накопления цели.
   * Пока не задан, накопления считаются отдельным активом — иначе введённое
   * «уже накоплено» нигде бы не учитывалось и капитал уходил бы в минус.
   */
  accountId?: string | null
}

export type WishItem = Tracked & {
  id: string
  name: string
  price: number
  by: PersonId
  addedOn: string
  url?: string
  bought: boolean
  boughtOn?: string | null
}

/**
 * Сумма обязательства не перезаписывается никогда. Каждое изменение —
 * новая версия с месяца, в котором она вступает в силу. Отсюда берётся
 * и история, и событие «освободилось N ₸ в месяц».
 */
export type ObligationVersion = {
  /** Ключ месяца вида «2026-11» */
  from: string
  amount: number
  reason?: string
}

export type Obligation = Tracked & {
  id: string
  name: string
  note: string
  /** День платежа */
  day: number
  category: CategoryKey
  versions: ObligationVersion[]
  /** Сумма плавает (коммуналка) — показываем как оценку, а не как факт. */
  estimate?: boolean
  /** Группа, в которой лежит подписка. Вынуть из группы — null, а не пусто (слияние). */
  parentId?: string | null
  /**
   * Группа подписок, а не платёж: своей суммы нет (итог — сумма детей), в бюджет,
   * календарь, «до зарплаты» и отметки не входит. Название свободное — справочника
   * групп нет, у каждой семьи свои.
   */
  group?: boolean
  /** Группа: «рабочие — не спрашивать» — её подпискам «оставить?» не задаётся. */
  noAsk?: boolean
  /**
   * Когда в последний раз решили «оставить» (и когда завели): по нему вопрос
   * «оставить?» не повторяется — и партнёру тоже, потому что живёт в общем документе.
   */
  keptAt?: string | null
  /**
   * Как часто платится. Пусто — ежемесячно.
   *
   * Годовое хранится годовой суммой, а не поделённым на двенадцать: страховка,
   * налог на транспорт и техосмотр списываются целиком и в конкретный месяц.
   * Если хранить их месячной долей, о списании нечем напомнить, а если считать
   * в бюджете полной суммой — одиннадцать месяцев из двенадцати он завышен.
   * Поэтому сумма настоящая, а в план месяца входит доля.
   */
  every?: 'month' | 'year'
  /** Месяц списания для годовых, 1–12. */
  month?: number
  /**
   * Чей это платёж. Пусто — общий.
   *
   * Личного кошелька пока нет, но подписка бывает личной, и без этого поля она
   * растворяется в общем счёте. Когда кошелёк появится, поле переедет туда без
   * переделки данных.
   */
  who?: PersonId | null
}

export type Currency = 'KZT' | 'USD' | 'EUR' | 'RUB'

export type Account = Tracked & {
  id: string
  name: string
  note: string
  /**
   * Всегда в тенге — по нему считается капитал.
   *
   * В документе это база: остаток на момент последней ручной сверки. Видимый
   * остаток — база минус отметки платежей после сверки (finance.ts
   * `accountBalance`); стор отдаёт экранам уже его.
   */
  amount: number
  /**
   * Когда остаток последний раз ввели руками. Отметки платежей до этого момента в
   * введённую сумму уже вошли и не списываются второй раз — иначе сверка с банком
   * удвоила бы оплаченное. Пусто — сверки не было, считаются все отметки.
   */
  amountSetAt?: string | null
  kind: 'card' | 'cash' | 'deposit' | 'envelope'
  /**
   * Валютный счёт хранит и сумму в валюте, и курс, по которому её перевели.
   * Курс вводится вручную и запоминается вместе с датой: так прошлые цифры
   * не переписываются при каждом скачке курса, а человек видит, по какому
   * курсу считалось.
   */
  currency?: Currency
  foreignAmount?: number
  rate?: number
  rateAt?: string
  deposit?: {
    annualRate: number
    months: number
    monthlyTopUp: number
    capitalize: boolean
  }
}

export type Credit = Tracked & {
  id: string
  name: string
  note: string
  /**
   * Остаток долга. В документе — база на момент ручного ввода, видимый остаток —
   * база минус тело по отметкам после него (finance.ts `creditBalance`).
   */
  principal: number
  /** Когда остаток долга последний раз ввели руками — якорь, как `Account.amountSetAt`. */
  principalSetAt?: string | null
  /** ГЭСВ — годовая эффективная ставка вознаграждения из договора. */
  annualRate: number
  payment: number
  day: number
}

/**
 * Отметка «оплатил» — запись, а не перезапись остатка (Р-7).
 *
 * Уменьшать остаток счёта и долга на месте нельзя: если оба отметили разные
 * платежи офлайн, при слиянии победила бы одна правка остатка, и второй платёж
 * молча пропал бы. Записи объединяются по id, как взносы в цели, а остатки
 * выводятся из них. Снять отметку — надгробие: запись перестаёт считаться, и
 * деньги возвращаются сами. Отметить снова — новая запись с новым id.
 */
export type Payment = Tracked & {
  id: string
  /** Платёж по графику обязательства, кредита — или досрочка по кредиту. */
  kind: 'obligation' | 'credit' | 'prepay'
  /** id обязательства или кредита. */
  targetId: string
  /**
   * Месяц платежа по графику, «2026-09»; у годовых — их месяц, у досрочки — месяц
   * применения. Одна пара (цель, месяц) — одна оплата, сколько бы телефонов её ни
   * отметили.
   */
  period: string
  /** Сколько списано, целые тенге. */
  amount: number
  /** Кредит и досрочка: сколько из суммы ушло в тело долга — снимок на момент отметки. */
  principal?: number
  /** С какого счёта списано; null — «не списывать». */
  accountId: string | null
  by: PersonId
  /** Когда отметили. По нему выбирается одна из двойных отметок и сравнивается якорь сверки. */
  at: string
  /**
   * Досрочка: сколько процентов не отдадим банку — снимок расчёта на момент
   * применения. Пересчитывать позже нечестно: остаток и платёж с тех пор меняются.
   */
  saved?: number
  /** Досрочка: «сократить срок» или «снизить платёж». */
  mode?: 'term' | 'payment'
  /**
   * «Снизить платёж» меняет `Credit.payment`; прежний хранится здесь, чтобы снятие
   * досрочки его вернуло, а новый — чтобы вернуть только если платёж с тех пор не меняли.
   */
  prevPayment?: number
  newPayment?: number
  /** Досрочка по выбранному плану «Сначала долги» (PV-14): id плана. */
  planId?: string
}

/** Прогноз плана: выигрыш к горизонту, сэкономленные проценты, месяц без процентных долгов. */
export type PlanForecast = {
  /** Насколько «Сначала долги» богаче «копим как сейчас» к горизонту, ₸. */
  gain: number
  /**
   * Сколько процентов не отдадим банку за всё время, ₸. null — считать не с чем: без плана
   * (или с ним) долг не закрывается, платёж не покрывает проценты (Р-11).
   */
  savedInterest: number | null
  /** Месяц «2027-05», когда закроется последний долг с процентами; null — не закрывается. */
  debtFreeMonth: string | null
}

/**
 * Выбранный план «Сначала долги» (Р-4, Р-9): живёт в общем документе, его видят оба.
 * Пауза целей из него выводится (`pausedGoals`) и в цели не пишется: `Goal.monthly`
 * не меняется, отмена плана цели не правит. Активный — один (при двух после слияния
 * побеждает поздний), завершённые и отменённые остаются историей.
 */
export type DebtPlan = Tracked & {
  id: string
  status: 'active' | 'done' | 'cancelled'
  by: PersonId
  /** Когда выбрали; месяц старта — `monthKey(startedAt)` по Алматы. */
  startedAt: string
  endedAt?: string | null
  /** «Что не останавливать»: взносы этих целей идут как раньше. */
  keptGoalIds: string[]
  /** Цель-подушка (Р-7): взносы продолжаются, пока в ней меньше месяца списаний — шаг плана в неё. */
  cushionGoalId: string | null
  /** Процентные долги на момент выбора: их платёж после закрытия идёт в план (Р-5). */
  creditIds: string[]
  months: 12 | 24 | 36
  /** «Вложить уже накопленное» — взнос месяца старта; 0 — нет. */
  lump: number
  /** Прогноз на момент выбора (Р-6). */
  forecast: PlanForecast
  /** Итог завершённого или отменённого плана (Р-5). */
  result?: { savedInterest: number } | null
}

/** Документ, который ездит между устройствами. Настройки оформления в него не входят: */
/** тема и цвета — дело устройства, партнёр не должен перекрашивать чужое приложение. */
export type SyncDoc = {
  people: Person[]
  categories: Category[]
  goals: Goal[]
  wishlist: WishItem[]
  obligations: Obligation[]
  accounts: Account[]
  credits: Credit[]
  /** Отметки оплат. Документы до Блока 1 приходят без этого ключа. */
  payments?: Payment[]
  /** Планы «Сначала долги» (PV-14). Документы до Блока 3 паритета приходят без ключа. */
  plans?: DebtPlan[]
  /**
   * Когда закончили первичную настройку бюджета. Пустое значит, что показываем
   * мастер. Живёт в общем документе, а не в настройках устройства: второй
   * участник, зайдя со своего телефона, не должен снова проходить настройку
   * жилья и кредитов — у него будет только свой короткий шаг про доход.
   */
  setupDoneAt?: string | null
}

export type SyncStatus = 'offline' | 'idle' | 'syncing' | 'dirty' | 'error' | 'conflict'

