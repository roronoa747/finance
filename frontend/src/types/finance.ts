/**
 * Сумма обязательства не перезаписывается никогда. Каждое изменение —
 * новая версия с месяца, в котором она вступает в силу. Отсюда берётся
 * и история, и событие «освободилось N ₸ в месяц».
 */
export type ObligationVersion = {
  /** Ключ месяца вида «2026-11» */
  from: string
  /** Сумма — целые единицы своей валюты (`currency`, нет — тенге), без центов (Р-70). */
  amount: number
  reason?: string
  /** Валюта версии (оклад — B2C-78, платёж — B2C-81); нет — KZT. */
  currency?: Currency
  /** Курс Нацбанка на момент ввода — запасной, когда в книге нет дня (Р-70, Р-72). */
  rate?: number
}

export type Obligation = Tracked & {
  id: string
  name: string
  note: string
  /** День платежа */
  day: number
  category: CategoryKey
  versions: ObligationVersion[]
  /** Сумма плавает (коммуналка) — показываем как оценку, а не как факт. */
  estimate?: boolean
  /** Группа, в которой лежит подписка. Вынуть из группы — null, а не пусто (слияние). */
  parentId?: string | null
  /**
   * Группа подписок, а не платёж: своей суммы нет (итог — сумма детей), в бюджет,
   * календарь, «до зарплаты» и отметки не входит. Название свободное — справочника
   * групп нет, у каждой семьи свои.
   */
  group?: boolean
  /** Группа: «рабочие — не спрашивать» — её подпискам «оставить?» не задаётся. */
  noAsk?: boolean
  /**
   * Когда в последний раз решили «оставить» (и когда завели): по нему вопрос
   * «оставить?» не повторяется — и партнёру тоже, потому что живёт в общем документе.
   */
  keptAt?: string | null
  /**
   * Как часто платится. Пусто — ежемесячно.
   *
   * Годовое хранится годовой суммой, а не поделённым на двенадцать: страховка,
   * налог на транспорт и техосмотр списываются целиком и в конкретный месяц.
   * Если хранить их месячной долей, о списании нечем напомнить, а если считать
   * в бюджете полной суммой — одиннадцать месяцев из двенадцати он завышен.
   * Поэтому сумма настоящая, а в план месяца входит доля.
   */
  every?: 'month' | 'year'
  /** Месяц списания для годовых, 1–12. */
  month?: number
  /**
   * Чей это платёж. Пусто — общий.
   *
   * Личного кошелька пока нет, но подписка бывает личной, и без этого поля она
   * растворяется в общем счёте. Когда кошелёк появится, поле переедет туда без
   * переделки данных.
   */
  who?: PersonId | null
  /** Кто платит (Р-80): меняется в плане месяца с этого месяца дальше; пусто — `who`, иначе первый участник. */
  payer?: PersonId | null
  /**
   * Платёж людям (мелочи Р-5, Р-12): маме, алименты, школа. Остатка нет — в «Долгах» свёрнутой строкой
   * «Людям · N» (`peopleGroup`), в сумму долгов не входит; в плане месяца — обычный платёж, не подписка.
   */
  people?: boolean
}

export type Currency = 'KZT' | 'USD' | 'EUR' | 'RUB' | 'CNY'

/**
 * Книга курсов Нацбанка (B2C-77, Р-72): валюта → день «YYYY-MM-DD» → тенге за единицу.
 * Курс — не деньги: дробный, как опубликован; тенге из валюты — только `fxToTenge`.
 * Передаётся расчётам параметром (как `totals`, `uploads`), не глобалом.
 */
export type RateBook = Partial<Record<Currency, Record<string, number>>>

export type Account = Tracked & {
  id: string
  name: string
  note: string
  /**
   * Всегда в тенге — по нему считается капитал.
   *
   * В документе это база: остаток на момент последней ручной сверки. Видимый
   * остаток — база минус отметки платежей после сверки (finance.ts
   * `accountBalance`); стор отдаёт экранам уже его.
   */
  amount: number
  /**
   * Когда остаток последний раз ввели руками. Отметки платежей до этого момента в
   * введённую сумму уже вошли и не списываются второй раз — иначе сверка с банком
   * удвоила бы оплаченное. Пусто — сверки не было, считаются все отметки.
   */
  amountSetAt?: string | null
  kind: 'card' | 'cash' | 'deposit' | 'envelope'
  /**
   * Валютный счёт хранит и сумму в валюте, и курс, по которому её перевели.
   * Курс вводится вручную и запоминается вместе с датой: так прошлые цифры
   * не переписываются при каждом скачке курса, а человек видит, по какому
   * курсу считалось.
   */
  currency?: Currency
  foreignAmount?: number
  rate?: number
  rateAt?: string
  deposit?: {
    annualRate: number
    months: number
    monthlyTopUp: number
    capitalize: boolean
  }
}

export type Credit = Tracked & {
  id: string
  name: string
  note: string
  /**
   * Остаток долга. В документе — база на момент ручного ввода, видимый остаток —
   * база минус тело по отметкам после него (finance.ts `creditBalance`).
   */
  principal: number
  /** Когда остаток долга последний раз ввели руками — якорь, как `Account.amountSetAt`. */
  principalSetAt?: string | null
  /** ГЭСВ — годовая эффективная ставка вознаграждения из договора. */
  annualRate: number
  /**
   * Ставку не знаем (кредит из выписки в первом запуске, B2C-19): `annualRate` — 0 до уточнения, но
   * это не рассрочка — экраны пишут «ставку уточните», а не «без процентов». Правка ставки снимает (null).
   */
  rateUnknown?: boolean | null
  payment: number
  day: number
  /** Кто платит по графику (Р-80); пусто — первый участник семьи. */
  payer?: PersonId | null
  /**
   * Долг человеку (мелочи Р-5, Р-12): займ без процентов с именем — `annualRate` 0, `rateUnknown` нет. Считается
   * путём рассрочки (план не досрочит, Р-7); флаг — только показ: строка без ставки, «Отдал» вместо «Оплатил».
   */
  person?: boolean
}

/**
 * Отметка «оплатил» — запись, а не перезапись остатка (Р-7).
 *
 * Уменьшать остаток счёта и долга на месте нельзя: если оба отметили разные
 * платежи офлайн, при слиянии победила бы одна правка остатка, и второй платёж
 * молча пропал бы. Записи объединяются по id, как взносы в цели, а остатки
 * выводятся из них. Снять отметку — надгробие: запись перестаёт считаться, и
 * деньги возвращаются сами. Отметить снова — новая запись с новым id.
 */
export type Payment = Tracked & {
  id: string
  /**
   * Платёж по графику обязательства, кредита, досрочка по кредиту — или «пришла
   * зарплата» (RP-10): единственная запись-зачисление, остаток счёта от неё растёт.
   */
  kind: 'obligation' | 'credit' | 'prepay' | 'salary'
  /** id обязательства или кредита; у зарплаты — участник (`PersonId`). */
  targetId: string
  /**
   * Месяц платежа по графику, «2026-09»; у годовых — их месяц, у досрочки — месяц
   * применения, у зарплаты — месяц её дня. Одна пара (цель, месяц) — одна оплата,
   * сколько бы телефонов её ни отметили. У зарплаты не-месячного ритма (аванс, неделя —
   * понятность Б7) — ISO-день события «2026-10-02»; месяц — `periodMonth(period)`.
   */
  period: string
  /** Сколько списано (у зарплаты — зачислено), целые тенге. */
  amount: number
  /** Кредит и досрочка: сколько из суммы ушло в тело долга — снимок на момент отметки. */
  principal?: number
  /** С какого счёта списано (на какой зачислено); null — «не списывать». */
  accountId: string | null
  by: PersonId
  /** Когда отметили. По нему выбирается одна из двойных отметок и сравнивается якорь сверки. */
  at: string
  /**
   * Досрочка: сколько процентов не отдадим банку — снимок расчёта на момент
   * применения. Пересчитывать позже нечестно: остаток и платёж с тех пор меняются.
   */
  saved?: number
  /** Досрочка: «сократить срок» или «снизить платёж». */
  mode?: 'term' | 'payment'
  /**
   * «Снизить платёж» меняет `Credit.payment`; прежний хранится здесь, чтобы снятие
   * досрочки его вернуло, а новый — чтобы вернуть только если платёж с тех пор не меняли.
   */
  prevPayment?: number
  newPayment?: number
  /** Досрочка по выбранному плану «Сначала долги» (PV-14): id плана. */
  planId?: string
  /**
   * Откуда отметка (Р-6, B2C-15): руками («Оплатил» / «Пришла») или по строке выписки —
   * тогда `opId` — id операции (личной; партнёр видит только пометку источника).
   */
  source?: 'manual' | 'statement'
  opId?: string
  /**
   * Зарплата в валюте (B2C-79, Р-73): сколько пришло в валюте на валютный счёт; `amount` —
   * тенге по курсу Нацбанка на день прихода. Остаток валютного счёта растёт на `foreign`.
   */
  foreign?: number
  currency?: Currency
}

/**
 * Обмен валюты (B2C-79, Р-73): часть зарплаты продали по своему курсу. Запись неизменна,
 * отмена — надгробие (`deletedAt`). Валютный счёт теряет `foreign`, тенговый получает `tenge`.
 */
export type FxExchange = Tracked & {
  id: string
  /** Чья зарплата (участник). */
  by: PersonId
  /** Валютный счёт, с которого продали. */
  accountId: string
  /** Тенговый счёт зачисления; null — «не записывать на счёт». */
  toAccountId: string | null
  currency: Currency
  /** Сколько продали, целые единицы валюты. */
  foreign: number
  /** Курс обмена — вводит человек (тенге за единицу). */
  rate: number
  /** Тенге = `fxToTenge(foreign, rate)`, снимок на момент записи. */
  tenge: number
  /** Месяц зарплаты, к которой относится обмен. */
  period: string
  /** Когда обменяли. */
  at: string
}

/** Прогноз плана: выигрыш к горизонту, сэкономленные проценты, месяц без процентных долгов. */
export type PlanForecast = {
  /** Насколько «Сначала долги» богаче «копим как сейчас» к горизонту, ₸. */
  gain: number
  /**
   * Сколько процентов не отдадим банку за всё время, ₸. null — считать не с чем: без плана
   * (или с ним) долг не закрывается, платёж не покрывает проценты (Р-11).
   */
  savedInterest: number | null
  /** Месяц «2027-05», когда закроется последний долг с процентами; null — не закрывается. */
  debtFreeMonth: string | null
}

/**
 * Выбранный план «Сначала долги» (Р-4, Р-9): живёт в общем документе, его видят оба.
 * Пауза целей из него выводится (`pausedGoals`) и в цели не пишется: `Goal.monthly`
 * не меняется, отмена плана цели не правит. Активный — один (при двух после слияния
 * побеждает поздний), завершённые и отменённые остаются историей.
 */
export type DebtPlan = Tracked & {
  id: string
  status: 'active' | 'done' | 'cancelled'
  by: PersonId
  /** Когда выбрали; месяц старта — `monthKey(startedAt)` по Алматы. */
  startedAt: string
  endedAt?: string | null
  /** «Что не останавливать»: взносы этих целей идут как раньше. */
  keptGoalIds: string[]
  /** Цель-подушка (Р-7): взносы продолжаются, пока в ней меньше месяца списаний — шаг плана в неё. */
  cushionGoalId: string | null
  /** Процентные долги на момент выбора: их платёж после закрытия идёт в план (Р-5). */
  creditIds: string[]
  months: 12 | 24 | 36
  /** «Вложить уже накопленное» — взнос месяца старта; 0 — нет. */
  lump: number
  /** Прогноз на момент выбора (Р-6). */
  forecast: PlanForecast
  /** Итог завершённого или отменённого плана (Р-5). */
  result?: { savedInterest: number } | null
}

/**
 * Часть раскладки: цель (`goalId`), досрочка (`prepay:<creditId>`) или «качество жизни» (`life`).
 * У записи разбора (`kind: 'breakdown'`) — статья (`ArticleKey`).
 */
export type AllocationPart = { target: string; amount: number }

/**
 * Статья разбора зарплаты (Р-51, Р-56): порядок по умолчанию — Обязательное → Жизнь → Запас →
 * Дорогие долги → Подушка → Мечты → Траты. Ступени — это и есть порядок статей.
 */
export type ArticleKey = 'must' | 'life' | 'reserve' | 'debts' | 'cushion' | 'dreams' | 'spend'

/**
 * Статья плана разбора (B2C-54, Р-68): одна запись на статью, LWW по `id`. `amount` — целые
 * тенге: у «Жизни» и «Трат» — сумма месяца, у «Запаса», «Подушки», «Дорогих долгов» — взнос
 * месяца без плана «Сначала долги»; у «Обязательного» и «Мечт» суммы нет — они выводятся из
 * платежей месяца и взносов целей.
 */
export type MoneyArticle = Tracked & {
  id: ArticleKey
  order: number
  on: boolean
  amount?: number
}

/**
 * Пороги ступеней (B2C-54, Р-55, Р-66) — один объект на семью, целиком по позднему `updatedAt`.
 * Месяцы — целые; `costlyRate` — целые проценты годовых: долг «дорогой» при ставке не ниже.
 */
export type MoneySettings = Tracked & {
  reserveMonths: number
  cushionMonths: number
  costlyRate: number
  /** Цель-копилка «Запаса» и «Подушки» (Р-66); нет — создаётся при первом «Разложить». */
  potGoalId?: string | null
  /** Когда пройден «Ваш порядок»; null — первый разбор начинается с него (Р-55). */
  orderedAt?: string | null
}

/**
 * Раскладка разовой суммы (B2C-21): зарплата (`sourceId` — участник), остаток месяца (`sourceId` —
 * месяц) или освободившийся платёж (`sourceId` — кредит или обязательство) за период. Решение
 * записано — по этому же источнику и периоду второй раз не раскладываем.
 */
export type Allocation = Tracked & {
  id: string
  source: 'salary' | 'rest' | 'freed'
  /**
   * Запись разбора (B2C-54, Р-65): `parts` — по статьям (`target` = `ArticleKey`). Старые записи
   * без `kind` — раскладка по целям, читаются как были. `plan` — «Отложить по плану» (Р-78, B2C-86):
   * `parts` — цели и фонды (`goalId`) и досрочка (`prepay:<creditId>`), `total` — зарплата плательщика.
   */
  kind?: 'breakdown' | 'plan'
  /** Статьи, выключенные в этом разборе: «как обычно» в следующем месяце их не включает (Р-55). */
  off?: ArticleKey[]
  sourceId: string
  period: string
  by: PersonId
  at: string
  total: number
  parts: AllocationPart[]
}

/**
 * Сумма трат участника на месяц по разделу выписок (Р-81): одна запись на пару, `id` = `${by}:${categoryId}`,
 * LWW по id; переносится из месяца в месяц. Факт — `SpendTotal` `kind: 'month'` этого участника.
 */
export type SpendPlan = Tracked & {
  id: string
  by: PersonId
  categoryId: string
  /** Целые тенге в месяц. */
  amount: number
}

/**
 * Порядок очереди (Р-84): ids сверху вниз — объект целиком, поздний `updatedAt` побеждает (как
 * `moneySettings`). У целей — ids целей и фондов и `debt` (карточка долга), у «Желаний» — свой.
 */
export type QueueOrder = Tracked & { ids: string[] }

/**
 * Карточка «закрыть кредит» (Р-82, Р-83): досрочка самого дорогого долга своей суммой в месяц. Свой объект,
 * а не часть `goalOrder`: перестановка на одном телефоне не затирает сумму, поставленную на другом. Объект
 * целиком по позднему `updatedAt`.
 */
export type DebtCard = Tracked & {
  /** Целые тенге в месяц; с активным планом «Сначала долги» — шаг плана, а не эта сумма. */
  monthly: number
  pausedAt?: string | null
  /** Кто вносит досрочку (Р-80); пусто — первый участник семьи. */
  payer?: PersonId | null
}

/** Документ, который ездит между устройствами. Настройки оформления в него не входят: */
/** тема и цвета — дело устройства, партнёр не должен перекрашивать чужое приложение. */
export type SyncDoc = {
  people: Person[]
  categories: Category[]
  goals: Goal[]
  wishlist: WishItem[]
  obligations: Obligation[]
  accounts: Account[]
  credits: Credit[]
  /** Отметки оплат. Документы до Блока 1 приходят без этого ключа. */
  payments?: Payment[]
  /** Планы «Сначала долги» (PV-14). Документы до Блока 3 паритета приходят без ключа. */
  plans?: DebtPlan[]
  /** Разделы трат выписок (B2C-02, Р-22) — не разделы бюджета d1…d5. До Блока 1 B2C — без ключа. */
  spendCategories?: SpendCategory[]
  /** Итоги трат участников по разделам за неделю и месяц (Р-21); операции — личные, на сервере. */
  spendTotals?: SpendTotal[]
  /** Итоги трат участников за поездку (PN-30). До Блока 9 «понятность» — без ключа. */
  tripSpends?: TripSpend[]
  /** Записи разбора (Блок 11) и прежних раскладок (B2C-21): второй заход и партнёр видят решение, а не разбирают снова. */
  allocations?: Allocation[]
  /** План разбора зарплаты по статьям (B2C-54, Р-68). До Блока 11 — без ключа: умолчания `moneyArticlesOf`. */
  moneyArticles?: MoneyArticle[]
  /** Пороги фондов, ставка «дорогого» долга, копилка (B2C-54, Р-82); `orderedAt` — поле старых клиентов. До Блока 11 — без ключа. */
  moneySettings?: MoneySettings | null
  /** Обмены валютной зарплаты (B2C-79, Р-73). До Блока 13 — без ключа. */
  fxExchanges?: FxExchange[]
  /** Суммы трат каждого по разделам (Р-81, B2C-85). До Блока 14 — без ключа. */
  spendPlans?: SpendPlan[]
  /** Порядок очереди целей, фондов и карточки долга (Р-84). До Блока 14 — без ключа: старый `main` первым. */
  goalOrder?: QueueOrder | null
  /** Порядок «Желаний» (Р-84). */
  wishOrder?: QueueOrder | null
  /** Карточка «закрыть кредит» (Р-82). */
  debtCard?: DebtCard | null
  /** Разборы месяца ИИ (бэклог «ИИ», AI-09): не больше 12 живых, старые — надгробия. До Блока 2 «ИИ» — без ключа. */
  aiReviews?: AiReview[]
  /** Снимки срока мечт на начало месяца (бэклог «ИИ-польза», Р-6, AU-04): не больше 3 живых. До Блока 2 — без ключа. */
  termSnaps?: TermSnap[]
  /** Сдвиги месяца «Сделать» / «Вернуть срок» (бэклог «ИИ-польза», Р-17, AU-05): отмена — надгробие. До Блока 2 — без ключа. */
  planShifts?: PlanShift[]
  /** Итоги привычек трат участников за месяц (бэклог «ИИ-польза», Р-24, AU-27): только счётчик и сумма. До Блока 7 — без ключа. */
  habitTotals?: HabitTotal[]
  /**
   * Итоги находок участников за месяц (бэклог «Разбор», Р-13, RZ-01): продавцы, разделы, счётчики и суммы — без дат и
   * людей. До Блока 1 «Разбор» — без ключа.
   */
  reviewFinds?: ReviewFind[]
  /** Переносы «в мечту» у образов (бэклог «ИИ-польза», Х-9, AU-31): отмена — надгробие. До AU-31 — без ключа. */
  imageMoves?: ImageMove[]
  /**
   * Когда закончили первичную настройку бюджета. Пустое значит, что показываем
   * первый запуск (`/start`). Живёт в общем документе, а не в настройках устройства: второй
   * участник, зайдя со своего телефона, не должен снова проходить настройку
   * жилья и кредитов — у него будет только свой короткий шаг про доход.
   */
  setupDoneAt?: string | null
  /**
   * Когда бюджет последний раз начали заново («Начать бюджет заново», PV-21). Документ
   * со свежей меткой побеждает при слиянии целиком: иначе телефон партнёра слиянием по
   * id вернул бы всё стёртое. Документы без сброса приходят без ключа.
   */
  resetAt?: string | null
}

