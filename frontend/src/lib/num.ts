/**
 * Разбор и показ чисел в полях ввода. Отдельно от компонента, потому что это
 * чистые правила и их надо уметь проверять без браузера.
 */

const NBSP = ' '

/** Цифры и запятая — всё, что имеет значение для положения курсора. */
export const SIG = /[\d,]/

export type NumKind = 'money' | 'int' | 'rate'

/**
 * Приводит набранное к показываемому виду.
 *
 * Ноль не залипает. В поле со значением «0» набранная пятёрка давала «05», а
 * если курсор стоял перед нулём — «50». Поэтому правил два: ведущий ноль уходит,
 * как только за ним появляется цифра, и отдельно — если поле показывало ровно
 * «0», добавленная цифра вытесняет его с любой стороны. Для этого нужно знать
 * прежнее значение: по одной строке «50» не отличить от честно набранного.
 * Одиночный «0» и «0,5» остаются — это законные значения.
 *
 * Суммы разбиваются на разряды: подсказки в полях и так написаны как
 * «600 000», и сплошная лента цифр рядом с ними читалась плохо.
 */
export function clean(s: string, kind: NumKind, prev?: string): string {
  if (prev === '0' && /^(\d0|0\d)$/.test(s)) s = s.replace('0', '')
  if (kind === 'rate') {
    const only = s.replace(/[^\d.,]/g, '').replace(/\./g, ',')
    const i = only.indexOf(',')
    const one = i < 0 ? only : only.slice(0, i + 1) + only.slice(i + 1).replace(/,/g, '')
    return one.replace(/^0+(?=\d)/, '')
  }
  const d = s.replace(/\D/g, '').replace(/^0+(?=\d)/, '')
  return kind === 'int' ? d : d.replace(/\B(?=(\d{3})+(?!\d))/g, NBSP)
}

/**
 * Куда поставить курсор после перерисовки. Разряды сдвигают текст, поэтому
 * курсор возвращается не на прежний индекс символа, а туда, где слева от него
 * столько же значащих знаков, сколько было. Иначе он прыгал бы в конец при
 * каждом появлении пробела.
 */
export function caretAt(text: string, sig: number): number {
  if (sig <= 0) return 0
  let seen = 0
  for (let i = 0; i < text.length; i++) {
    if (SIG.test(text[i])) seen++
    if (seen >= sig) return i + 1
  }
  return text.length
}

/** Сколько значащих знаков слева от курсора. */
export function sigBefore(text: string): number {
  return (text.match(/[\d,]/g) ?? []).length
}
