const sum = (o: Record<string, number>) => Object.values(o).reduce((a, v) => a + v, 0)

/** База долей: потребительские расходы без «Обязательного». */
export const STAT_BASE = STAT_CONSUMER_TOTAL - sum(STAT_MUST)

/** Ориентир: раздел → целая доля в процентах от трат без «Обязательного»; нулевые — без черты. */
export const STAT_NORMS: Record<string, number> = Object.fromEntries(
  Object.entries(STAT_SOURCE)
    .map(([id, rows]) => [id, Math.round((sum(rows) * 100) / STAT_BASE)] as const)
    .filter(([, share]) => share > 0),
)

